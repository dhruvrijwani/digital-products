// Regenerates the file:// fallback mirrors for every idea's mock data.
//
// Each demo fetches data/<name>.json when served over http (npx serve).
// Browsers block fetch() on file://, so each data/<name>.json also gets a
// data/<name>.js mirror that sets window.__PROTO_DATA__[name]. The JSON stays
// the source of truth: edit it, then run `node tools/sync-data.mjs`.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

for (const idea of readdirSync(root).filter((d) => /^idea-\d\d$/.test(d))) {
  const dataDir = join(root, idea, "data");
  if (!existsSync(dataDir)) continue;
  for (const file of readdirSync(dataDir).filter((f) => f.endsWith(".json"))) {
    const name = file.replace(/\.json$/, "");
    const json = JSON.parse(readFileSync(join(dataDir, file), "utf8"));
    const js =
      "// Generated by tools/sync-data.mjs from " + file + ". Edit the JSON, not this file.\n" +
      "window.__PROTO_DATA__ = window.__PROTO_DATA__ || {};\n" +
      `window.__PROTO_DATA__[${JSON.stringify(name)}] = ${JSON.stringify(json)};\n`;
    writeFileSync(join(dataDir, name + ".js"), js);
    console.log("synced", `${idea}/data/${name}.js`);
  }
}
